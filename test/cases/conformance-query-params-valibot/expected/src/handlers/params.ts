import { Hono } from 'hono'
import { describeRoute, validator } from 'hono-openapi'
import * as v from 'valibot'
import { FieldsResponse } from '../components'

export const paramsHandler = new Hono().get(
  '/params',
  describeRoute({ operationId: 'queryParams', responses: { '200': FieldsResponse } }),
  validator(
    'query',
    v.partial(
      v.object({
        integer: v.pipe(v.string(), v.transform(Number), v.number(), v.integer()),
        integer_arr: v.array(v.pipe(v.string(), v.transform(Number), v.number(), v.integer())),
        int32: v.pipe(v.string(), v.transform(Number), v.number(), v.integer()),
        int32_arr: v.array(v.pipe(v.string(), v.transform(Number), v.number(), v.integer())),
        int64: v.pipe(v.string(), v.transform(Number), v.number(), v.integer()),
        int64_arr: v.array(v.pipe(v.string(), v.transform(Number), v.number(), v.integer())),
        bigint: v.pipe(v.string(), v.transform(Number), v.bigint()),
        bigint_arr: v.array(v.pipe(v.string(), v.transform(Number), v.bigint())),
        uint32: v.pipe(v.string(), v.transform(Number), v.number(), v.integer()),
        uint32_arr: v.array(v.pipe(v.string(), v.transform(Number), v.number(), v.integer())),
        uint64: v.pipe(v.string(), v.transform(Number), v.number(), v.integer()),
        uint64_arr: v.array(v.pipe(v.string(), v.transform(Number), v.number(), v.integer())),
        number: v.pipe(v.string(), v.transform(Number), v.number()),
        number_arr: v.array(v.pipe(v.string(), v.transform(Number), v.number())),
        float: v.pipe(v.string(), v.transform(Number), v.number()),
        float_arr: v.array(v.pipe(v.string(), v.transform(Number), v.number())),
        float32: v.pipe(v.string(), v.transform(Number), v.number()),
        float32_arr: v.array(v.pipe(v.string(), v.transform(Number), v.number())),
        float64: v.pipe(v.string(), v.transform(Number), v.number()),
        float64_arr: v.array(v.pipe(v.string(), v.transform(Number), v.number())),
        double: v.pipe(v.string(), v.transform(Number), v.number()),
        double_arr: v.array(v.pipe(v.string(), v.transform(Number), v.number())),
        numpassword: v.pipe(v.string(), v.transform(Number), v.number()),
        numpassword_arr: v.array(v.pipe(v.string(), v.transform(Number), v.number())),
        boolean: v.pipe(
          v.picklist(['true', 'false']),
          v.transform((input) => input === 'true'),
        ),
        boolean_arr: v.array(
          v.pipe(
            v.picklist(['true', 'false']),
            v.transform((input) => input === 'true'),
          ),
        ),
        string: v.string(),
        string_arr: v.array(v.string()),
        email: v.pipe(v.string(), v.email()),
        email_arr: v.array(v.pipe(v.string(), v.email())),
        uuid: v.pipe(v.string(), v.uuid()),
        uuid_arr: v.array(v.pipe(v.string(), v.uuid())),
        uuidv4: v.string(),
        uuidv4_arr: v.array(v.string()),
        uuidv7: v.string(),
        uuidv7_arr: v.array(v.string()),
        url: v.string(),
        url_arr: v.array(v.string()),
        uri: v.pipe(v.string(), v.url()),
        uri_arr: v.array(v.pipe(v.string(), v.url())),
        httpurl: v.string(),
        httpurl_arr: v.array(v.string()),
        hostname: v.string(),
        hostname_arr: v.array(v.string()),
        hex: v.string(),
        hex_arr: v.array(v.string()),
        emoji: v.pipe(v.string(), v.emoji()),
        emoji_arr: v.array(v.pipe(v.string(), v.emoji())),
        base64: v.pipe(v.string(), v.base64()),
        base64_arr: v.array(v.pipe(v.string(), v.base64())),
        base64url: v.string(),
        base64url_arr: v.array(v.string()),
        nanoid: v.string(),
        nanoid_arr: v.array(v.string()),
        cuid2: v.string(),
        cuid2_arr: v.array(v.string()),
        ulid: v.string(),
        ulid_arr: v.array(v.string()),
        ipv4: v.pipe(v.string(), v.ipv4()),
        ipv4_arr: v.array(v.pipe(v.string(), v.ipv4())),
        ipv6: v.pipe(v.string(), v.ipv6()),
        ipv6_arr: v.array(v.pipe(v.string(), v.ipv6())),
        cidrv4: v.string(),
        cidrv4_arr: v.array(v.string()),
        cidrv6: v.string(),
        cidrv6_arr: v.array(v.string()),
        date: v.pipe(v.string(), v.isoDate()),
        date_arr: v.array(v.pipe(v.string(), v.isoDate())),
        time: v.pipe(v.string(), v.isoTimeSecond()),
        time_arr: v.array(v.pipe(v.string(), v.isoTimeSecond())),
        datetime: v.pipe(v.string(), v.isoTimestamp()),
        datetime_arr: v.array(v.pipe(v.string(), v.isoTimestamp())),
        duration: v.string(),
        duration_arr: v.array(v.string()),
        byte: v.string(),
        byte_arr: v.array(v.string()),
        strpassword: v.string(),
        strpassword_arr: v.array(v.string()),
        mac: v.string(),
        mac_arr: v.array(v.string()),
        e164: v.string(),
        e164_arr: v.array(v.string()),
        creditcard: v.string(),
        creditcard_arr: v.array(v.string()),
        iban: v.string(),
        iban_arr: v.array(v.string()),
        currencycode: v.string(),
        currencycode_arr: v.array(v.string()),
        ksuid: v.string(),
        ksuid_arr: v.array(v.string()),
        xid: v.string(),
        xid_arr: v.array(v.string()),
        guid: v.string(),
        guid_arr: v.array(v.string()),
        tx_trim: v.pipe(v.string(), v.trim()),
        tx_lower: v.pipe(v.string(), v.toLowerCase()),
        tx_upper: v.pipe(v.string(), v.toUpperCase()),
        tx_normalize: v.pipe(v.string(), v.normalize('NFKC')),
        tx_email_trim: v.pipe(v.string(), v.trim(), v.email()),
        tx_uuid_trim: v.pipe(v.string(), v.trim(), v.uuid()),
        tx_email_lower: v.pipe(v.string(), v.toLowerCase(), v.email()),
      }),
    ),
  ),
  (c) => {},
)
