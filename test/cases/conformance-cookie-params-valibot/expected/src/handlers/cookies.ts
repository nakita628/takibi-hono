import { Hono } from 'hono'
import { describeRoute, validator } from 'hono-openapi'
import * as v from 'valibot'
import { FieldsResponse } from '../components'

export const cookiesHandler = new Hono().get(
  '/cookies',
  describeRoute({ operationId: 'cookieParams', responses: { '200': FieldsResponse } }),
  validator(
    'cookie',
    v.partial(
      v.object({
        integer: v.pipe(v.number(), v.integer()),
        int32: v.pipe(v.number(), v.integer()),
        int64: v.pipe(v.number(), v.integer()),
        bigint: v.bigint(),
        uint32: v.pipe(v.number(), v.integer()),
        uint64: v.pipe(v.number(), v.integer()),
        number: v.number(),
        float: v.number(),
        float32: v.number(),
        float64: v.number(),
        double: v.number(),
        numpassword: v.number(),
        boolean: v.boolean(),
        string: v.string(),
        email: v.pipe(v.string(), v.email()),
        uuid: v.pipe(v.string(), v.uuid()),
        uuidv4: v.string(),
        uuidv7: v.string(),
        url: v.string(),
        uri: v.pipe(v.string(), v.url()),
        httpurl: v.string(),
        hostname: v.string(),
        hex: v.string(),
        emoji: v.pipe(v.string(), v.emoji()),
        base64: v.pipe(v.string(), v.base64()),
        base64url: v.string(),
        nanoid: v.string(),
        cuid2: v.string(),
        ulid: v.string(),
        ipv4: v.pipe(v.string(), v.ipv4()),
        ipv6: v.pipe(v.string(), v.ipv6()),
        cidrv4: v.string(),
        cidrv6: v.string(),
        date: v.pipe(v.string(), v.isoDate()),
        time: v.pipe(v.string(), v.isoTimeSecond()),
        datetime: v.pipe(v.string(), v.isoTimestamp()),
        duration: v.string(),
        byte: v.string(),
        strpassword: v.string(),
        mac: v.string(),
        e164: v.string(),
        creditcard: v.string(),
        iban: v.string(),
        currencycode: v.string(),
        ksuid: v.string(),
        xid: v.string(),
        guid: v.string(),
        ids: v.array(v.pipe(v.number(), v.integer())),
      }),
    ),
  ),
  (c) => {},
)
