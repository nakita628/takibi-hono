import { Hono } from 'hono'
import { describeRoute, validator } from 'hono-openapi'
import * as v from 'valibot'
import { FieldsResponse } from '../components'

export const headersHandler = new Hono().get(
  '/headers',
  describeRoute({ operationId: 'headerParams', responses: { '200': FieldsResponse } }),
  validator(
    'header',
    v.partial(
      v.object({
        'x-integer': v.pipe(v.number(), v.integer()),
        'x-int32': v.pipe(v.number(), v.integer()),
        'x-int64': v.pipe(v.number(), v.integer()),
        'x-bigint': v.bigint(),
        'x-uint32': v.pipe(v.number(), v.integer()),
        'x-uint64': v.pipe(v.number(), v.integer()),
        'x-number': v.number(),
        'x-float': v.number(),
        'x-float32': v.number(),
        'x-float64': v.number(),
        'x-double': v.number(),
        'x-numpassword': v.number(),
        'x-boolean': v.boolean(),
        'x-string': v.string(),
        'x-email': v.pipe(v.string(), v.email()),
        'x-uuid': v.pipe(v.string(), v.uuid()),
        'x-uuidv4': v.string(),
        'x-uuidv7': v.string(),
        'x-url': v.string(),
        'x-uri': v.pipe(v.string(), v.url()),
        'x-httpurl': v.string(),
        'x-hostname': v.string(),
        'x-hex': v.string(),
        'x-base64': v.pipe(v.string(), v.base64()),
        'x-base64url': v.string(),
        'x-nanoid': v.string(),
        'x-cuid2': v.string(),
        'x-ulid': v.string(),
        'x-ipv4': v.pipe(v.string(), v.ipv4()),
        'x-ipv6': v.pipe(v.string(), v.ipv6()),
        'x-cidrv4': v.string(),
        'x-cidrv6': v.string(),
        'x-date': v.pipe(v.string(), v.isoDate()),
        'x-time': v.pipe(v.string(), v.isoTimeSecond()),
        'x-datetime': v.pipe(v.string(), v.isoTimestamp()),
        'x-duration': v.string(),
        'x-byte': v.string(),
        'x-strpassword': v.string(),
        'x-mac': v.string(),
        'x-e164': v.string(),
        'x-creditcard': v.string(),
        'x-iban': v.string(),
        'x-currencycode': v.string(),
        'x-ksuid': v.string(),
        'x-xid': v.string(),
        'x-guid': v.string(),
        'x-ids': v.array(v.pipe(v.number(), v.integer())),
      }),
    ),
  ),
  (c) => {},
)
