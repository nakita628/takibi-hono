import { Hono } from 'hono'
import { describeRoute, validator } from 'hono-openapi'
import * as z from 'zod'
import { FieldsResponse } from '../components'

export const headersHandler = new Hono().get(
  '/headers',
  describeRoute({ operationId: 'headerParams', responses: { '200': FieldsResponse } }),
  validator(
    'header',
    z.object({
      'x-integer': z.int().exactOptional(),
      'x-int32': z.int32().exactOptional(),
      'x-int64': z.int64().exactOptional(),
      'x-bigint': z.bigint().exactOptional(),
      'x-uint32': z.int().exactOptional(),
      'x-uint64': z.int().exactOptional(),
      'x-number': z.number().exactOptional(),
      'x-float': z.float32().exactOptional(),
      'x-float32': z.float32().exactOptional(),
      'x-float64': z.float64().exactOptional(),
      'x-double': z.number().exactOptional(),
      'x-numpassword': z.number().exactOptional(),
      'x-boolean': z.boolean().exactOptional(),
      'x-string': z.string().exactOptional(),
      'x-email': z.email().exactOptional(),
      'x-uuid': z.uuid().exactOptional(),
      'x-uuidv4': z.uuidv4().exactOptional(),
      'x-uuidv7': z.uuidv7().exactOptional(),
      'x-url': z.string().exactOptional(),
      'x-uri': z.url().exactOptional(),
      'x-httpurl': z.string().exactOptional(),
      'x-hostname': z.string().exactOptional(),
      'x-hex': z.string().exactOptional(),
      'x-base64': z.base64().exactOptional(),
      'x-base64url': z.base64url().exactOptional(),
      'x-nanoid': z.nanoid().exactOptional(),
      'x-cuid2': z.cuid2().exactOptional(),
      'x-ulid': z.ulid().exactOptional(),
      'x-ipv4': z.ipv4().exactOptional(),
      'x-ipv6': z.ipv6().exactOptional(),
      'x-cidrv4': z.cidrv4().exactOptional(),
      'x-cidrv6': z.cidrv6().exactOptional(),
      'x-date': z.iso.date().exactOptional(),
      'x-time': z.iso.time().exactOptional(),
      'x-datetime': z.iso.datetime().exactOptional(),
      'x-duration': z.iso.duration().exactOptional(),
      'x-byte': z.string().exactOptional(),
      'x-strpassword': z.string().exactOptional(),
      'x-mac': z.mac().exactOptional(),
      'x-e164': z.string().exactOptional(),
      'x-creditcard': z.string().exactOptional(),
      'x-iban': z.string().exactOptional(),
      'x-currencycode': z.string().exactOptional(),
      'x-ksuid': z.string().exactOptional(),
      'x-xid': z.string().exactOptional(),
      'x-guid': z.string().exactOptional(),
      'x-ids': z.array(z.int()).exactOptional(),
    }),
  ),
  (c) => {},
)
